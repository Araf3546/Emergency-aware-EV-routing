#!/usr/bin/env python3
"""Build the demand-level emergency-dispatch route file for the seeded incidents.

Population (2) of contract section 11, decision 13.1: the scripted incident
responders. Their routes are NOT recomputed here. They are copied verbatim from the
duarouter-validated file produced by scripts/09, so the Gate D validation still holds.

Two things are added on top of the validated routes:

  * departLane="free", departPos="free", departSpeed="max" - without these the
    responder sits in SUMO's insertion queue behind ordinary traffic and never enters
    the simulation at all (observed: emergency_dispatch_401 pending from t=781 to the
    end of the run). A responder that cannot get onto the network cannot be measured.
  * a cross-check that every dispatch matches scenarios/emergency_scenarios.yaml on
    vehicle id, type, departure time and destination edge.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from xml.etree import ElementTree as ET

try:
    import yaml
except ImportError:
    yaml = None


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file_handle:
        for chunk in iter(lambda: file_handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validated-routes", type=Path,
                        default=Path("network/validation/emergency_dispatch_validation.rou.xml"))
    parser.add_argument("--scenario", type=Path, default=Path("scenarios/emergency_scenarios.yaml"))
    parser.add_argument("--output", type=Path, default=Path("demand/porto.dispatch.rou.xml"))
    parser.add_argument("--report", type=Path, default=Path("demand/emergency_dispatch_demand.json"))
    parser.add_argument("--depart-lane", default="free")
    parser.add_argument("--depart-pos", default="free")
    parser.add_argument("--depart-speed", default="max")
    # Deliberately NOT the ambient fleet's 16.67 m/s cap: several edges here are posted
    # at up to 27.8 m/s, so a 16.67 cap would make the measured responders SLOWER than
    # ordinary traffic on the fast roads. 27.8 lets the road's own limit govern, and
    # speedFactor gives the responder its priority advantage.
    parser.add_argument("--max-speed", type=float, default=27.8)
    parser.add_argument("--speed-factor", type=float, default=1.2)
    arguments = parser.parse_args()

    for path in (arguments.validated_routes, arguments.scenario):
        if not path.is_file():
            parser.error(f"Required file not found: {path}")
    if yaml is None:
        parser.error("PyYAML is required to cross-check the emergency scenario file")

    scenario = yaml.safe_load(arguments.scenario.read_text(encoding="utf-8"))
    expected = {}
    for event in scenario.get("events", []):
        dispatch = event.get("dispatch")
        if dispatch:
            expected[str(dispatch["vehicle_id"])] = {
                "event_id": event.get("event_id"),
                "vehicle_type": str(dispatch.get("vehicle_type", "")),
                "departure_time": float(dispatch.get("departure_time")),
                "destination_edge": str(dispatch.get("destination_edge", "")),
                "incident_start": float(event["start_time"]) if event.get("start_time") is not None else None,
                "incident_end": float(event["end_time"]) if event.get("end_time") is not None else None,
            }

    tree = ET.parse(arguments.validated_routes)
    root = tree.getroot()

    # The validated file declares bare vTypes (`<vType id="ambulance" vClass="emergency"/>`),
    # so the three measured responders would otherwise run on SUMO defaults - slower than
    # the ambient emergency fleet generated by scripts/10, which is backwards for the
    # vehicles that carry the thesis's headline metric. Give them the same profile.
    for vtype in root.findall("vType"):
        vtype.set("accel", "2.9")
        vtype.set("decel", "5.0")
        vtype.set("sigma", "0.5")
        vtype.set("length", "6.5")
        vtype.set("minGap", "2.5")
        vtype.set("maxSpeed", str(arguments.max_speed))
        vtype.set("speedFactor", str(arguments.speed_factor))

    checks = []
    for vehicle in root.findall("vehicle"):
        vehicle_id = vehicle.attrib["id"]
        vehicle.set("departLane", arguments.depart_lane)
        vehicle.set("departPos", arguments.depart_pos)
        vehicle.set("departSpeed", arguments.depart_speed)

        route_element = vehicle.find("route")
        edges = route_element.attrib["edges"].split() if route_element is not None else []
        reference = expected.get(vehicle_id)

        # The scenario file is the source of truth for WHEN a responder departs; the
        # validated route file is the source of truth for WHICH edges it takes. The
        # validated file still carries the old v1 departure times, so the scenario's
        # value is written in here. Changing a departure time does not affect route
        # validity, so the Gate D reachability proof is unaffected.
        validated_depart = float(vehicle.attrib["depart"])
        if reference:
            vehicle.set("depart", f"{reference['departure_time']:.2f}")

        checks.append({
            "vehicle_id": vehicle_id,
            "in_scenario_file": reference is not None,
            "type_matches": bool(reference) and vehicle.attrib.get("type") == reference["vehicle_type"],
            "destination_matches": bool(reference) and bool(edges) and edges[-1] == reference["destination_edge"],
            "depart": float(vehicle.attrib["depart"]),
            "depart_in_validated_file": validated_depart,
            "depart_taken_from_scenario": bool(reference),
            "departs_after_incident_start": (
                bool(reference) and reference["incident_start"] is not None
                and float(vehicle.attrib["depart"]) > reference["incident_start"]
            ),
            "destination_edge": edges[-1] if edges else None,
            "route_edge_count": len(edges),
        })

    # Departure times may now differ from the validated file's order, so re-sort.
    vehicles = sorted(root.findall("vehicle"), key=lambda v: float(v.attrib["depart"]))
    for vehicle in root.findall("vehicle"):
        root.remove(vehicle)
    for vehicle in vehicles:
        root.append(vehicle)

    departs = [float(vehicle.attrib["depart"]) for vehicle in root.findall("vehicle")]
    departures_non_decreasing = all(departs[i] <= departs[i + 1] for i in range(len(departs) - 1))

    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    tree.write(arguments.output, encoding="utf-8", xml_declaration=True)

    all_matched = bool(checks) and all(
        check["in_scenario_file"] and check["type_matches"]
        and check["destination_matches"] and check["departs_after_incident_start"]
        for check in checks
    )
    missing = sorted(set(expected) - {check["vehicle_id"] for check in checks})

    report = {
        "report_version": 1,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "purpose": "Demand-level emergency dispatch routes (contract section 11, decision 13.1 population 2).",
        "inputs": {
            "validated_routes": str(arguments.validated_routes),
            "validated_routes_sha256": sha256(arguments.validated_routes),
            "scenario": str(arguments.scenario), "scenario_sha256": sha256(arguments.scenario),
        },
        "artifacts": {
            "route_file": str(arguments.output), "route_file_sha256": sha256(arguments.output),
        },
        "insertion_attributes": {
            "departLane": arguments.depart_lane,
            "departPos": arguments.depart_pos,
            "departSpeed": arguments.depart_speed,
            "rationale": "Without relaxed insertion the responder stays in SUMO's pending queue behind ordinary traffic and never enters the network.",
        },
        "routes_recomputed": False,
        "dispatch_count": len(checks),
        "dispatch_checks": checks,
        "missing_from_route_file": missing,
        "all_dispatches_match_scenario": all_matched and not missing,
        "departures_non_decreasing": departures_non_decreasing,
    }
    arguments.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    print(f"Wrote {arguments.output} with {len(checks)} dispatch vehicles")
    for check in checks:
        status = "OK" if (check["in_scenario_file"] and check["type_matches"]
                          and check["destination_matches"] and check["departs_after_incident_start"]) else "PROBLEM"
        print(f"  {check['vehicle_id']}: depart={check['depart']:.0f} "
              f"(was {check['depart_in_validated_file']:.0f}) dest={check['destination_edge']} "
              f"edges={check['route_edge_count']} after_incident_start={check['departs_after_incident_start']} {status}")
    if missing:
        print(f"FAILED: scenario dispatches missing from the route file: {missing}")
    if not departures_non_decreasing:
        print("FAILED: dispatch route file is not sorted by departure time.")

    return 0 if (all_matched and not missing and departures_non_decreasing) else 2


if __name__ == "__main__":
    raise SystemExit(main())
